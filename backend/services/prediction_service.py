import re
from functools import lru_cache

import torch


@lru_cache(maxsize=1)
def get_predictor():
    """
    Lazy-load the DistilGPT-2 text-generation pipeline on first use (B3).

    Previously loaded the ~320 MB model at import time, so every backend
    startup paid this cost even if nobody used Word Prediction that session.
    The transformers import is also deferred for the same reason.
    """
    from transformers import pipeline

    return pipeline(
        "text-generation",
        model="distilgpt2"
    )


# ---------------------------------------------------------------------------
# Word prediction
# ---------------------------------------------------------------------------

@lru_cache(maxsize=512)
def _predict_words_cached(prefix: str) -> tuple:
    """
    Generate up to 3 word predictions for a prefix.

    Results are cached so repeated requests for the same prefix do not
    repeatedly run the DistilGPT-2 model.
    """

    predictor = get_predictor()

    tokenizer = predictor.tokenizer
    model = predictor.model

    input_ids = tokenizer(
        prefix,
        return_tensors="pt"
    ).input_ids

    input_len = input_ids.shape[1]

    with torch.no_grad():
        output_ids = model.generate(
            input_ids,
            max_new_tokens=6,
            num_return_sequences=6,
            do_sample=True,
            temperature=0.8,
            pad_token_id=50256,
        )

    words = []

    for seq in output_ids:
        # Only inspect tokens generated after the user's prefix.
        new_tokens = seq[input_len:]

        generated_text = tokenizer.decode(
            new_tokens,
            skip_special_tokens=True
        )

        # Extract the first alphabetic word generated by the model.
        match = re.match(
            r"\s*([a-zA-Z]+)",
            generated_text
        )

        if match:
            word = match.group(1)

            # Avoid duplicate suggestions, ignoring case.
            if word.lower() not in [
                w.lower() for w in words
            ]:
                words.append(word)

        # Frontend displays at most 3 word suggestions.
        if len(words) == 3:
            break

    return tuple(words)


def predict_words(prefix: str) -> list[str]:
    """
    Return word predictions for the given prefix.

    Uses the cached generation function so repeated prefixes do not
    trigger repeated model inference.
    """

    if not prefix or not prefix.strip():
        return []

    prefix = prefix.rstrip()

    result = _predict_words_cached(prefix)

    return list(result)


# ---------------------------------------------------------------------------
# Phrase prediction
# ---------------------------------------------------------------------------

@lru_cache(maxsize=512)
def _predict_phrase_cached(prefix: str) -> str:
    """
    Generate a short phrase continuation.

    Results are cached so repeated requests for the same prefix do not
    repeatedly run the DistilGPT-2 model.
    """

    predictor = get_predictor()

    tokenizer = predictor.tokenizer
    model = predictor.model

    input_ids = tokenizer(
        prefix,
        return_tensors="pt"
    ).input_ids

    input_len = input_ids.shape[1]

    with torch.no_grad():
        output_ids = model.generate(
            input_ids,
            max_new_tokens=5,
            num_return_sequences=1,
            do_sample=True,
            temperature=0.7,
            pad_token_id=50256,
        )

    # Only decode tokens generated after the user's prefix.
    new_tokens = output_ids[0][input_len:]

    generated = tokenizer.decode(
        new_tokens,
        skip_special_tokens=True
    )

    # Stop the suggestion at the first period.
    phrase = generated.strip().split(".")[0]

    # Keep only letters, spaces and apostrophes.
    phrase = re.sub(
        r"[^a-zA-Z\s']",
        "",
        phrase
    ).strip()

    # PRD rule: unusable output returns an empty string.
    if not re.search(
        r"[a-zA-Z]",
        phrase
    ):
        return ""

    # Frontend limit: maximum 40 characters.
    return phrase[:40]


def predict_phrase(prefix: str) -> str:
    """
    Return a short phrase continuation for the given prefix.

    Uses the cached generation function so repeated prefixes do not
    trigger repeated model inference.
    """

    if not prefix or not prefix.strip():
        return ""

    prefix = prefix.rstrip()

    return _predict_phrase_cached(prefix)